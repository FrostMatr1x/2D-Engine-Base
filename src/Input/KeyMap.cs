    public static MouseButton ToEngineMouseButton(Silk.NET.Input.MouseButton button)
    {
        return button switch
        {
            Silk.NET.Input.MouseButton.Left => MouseButton.LeftButton,
            Silk.NET.Input.MouseButton.Right => MouseButton.RightButton,
            Silk.NET.Input.MouseButton.Middle => MouseButton.MiddleButton,
            _ => MouseButton.Null
        };
    }
